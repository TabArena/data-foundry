def _git(repo: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", "-C", str(repo), *args], check=check, capture_output=True, text=True)


def _last_commit_with(repo: Path, path: str) -> tuple[str, str | None] | None:
    """The last commit that still had ``path``, and the date of the commit that removed it.

    A file removed only in the working tree gives HEAD and no date; a file never committed gives None.
    """
    gone = _git(repo, "log", "-1", "--format=%H %ad", "--date=short", "--diff-filter=D", "--", path).stdout.split()
    if gone:
        return _git(repo, "rev-parse", f"{gone[0]}^").stdout.strip(), gone[1]
    if _git(repo, "cat-file", "-e", f"HEAD:{path}", check=False).returncode == 0:
        return _git(repo, "rev-parse", "HEAD").stdout.strip(), None
    return None


def _show(repo: Path, commit: str, path: str) -> str | None:
    shown = _git(repo, "show", f"{commit}:{path}", check=False)
    return shown.stdout if shown.returncode == 0 else None


def render(text: str) -> str:
    """Markdown to HTML (raw HTML in the source is escaped)."""
    return MD.render(text.strip()) if text.strip() else ""


def _frontmatter(text: str | None) -> tuple[dict, str]:
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text or "", re.S)
    return ((yaml.safe_load(m.group(1)) or {}), m.group(2)) if m else ({}, text or "")


def _readme(folder_dir: Path, wc_path: str, github: str) -> dict | None:
    """The folder's generated README.md: its YAML frontmatter as text, its body as HTML.

    Figures are embedded as data URIs; relative links point to the file on GitHub.
    """
    path = folder_dir / "README.md"
    if not path.exists():
        return None
    text = path.read_text()
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    front, body = (m.group(1), m.group(2)) if m else ("", text)
    out = MD_README.render(body)

    def image(match: re.Match) -> str:
        file = folder_dir / match.group(1)
        if file.suffix.lower() == ".png" and file.exists():
            return 'src="data:image/png;base64,' + base64.b64encode(file.read_bytes()).decode() + '"'
        return match.group(0)

    def link(match: re.Match) -> str:
        return 'href="' + github + posixpath.normpath(f"{wc_path}/{match.group(1)}") + '"'

    out = re.sub(r'src="([^":#]+)"', image, out)
    out = re.sub(r'href="(?!https?:|#|mailto:)([^"]+)"', link, out)
    return {"front": front, "html": out}


def _record(path: Path) -> dict:
    """The record's frontmatter as rows and its body as HTML."""
    meta, body = _frontmatter(path.read_text())
    rows = []
    for k, v in meta.items():
        value = ", ".join(str(x) for x in v) if isinstance(v, list) else v
        rows.append([k, "" if value is None else str(value)])
    return {"fields": rows, "html": render(body)}


def _decided(path: Path) -> dict | None:
    """The triage verdict of a record that already says No (verified, not reviewed for shipping), else None."""
    meta, body = _frontmatter(path.read_text())
    if not str(meta.get("suggestion") or "").startswith("No"):
        return None
    notes = [p.strip() for p in re.split(r"\n\s*\n", body) if p.strip().startswith("CC (")]
    return {
        "suggestion": str(meta.get("suggestion")),
        "markers": [str(x) for x in meta.get("decision_markers") or []],
        "checkedBy": [str(x) for x in meta.get("checked_by") or []],
        "ccHtml": render(notes[-1]) if notes else "",
    }


def _meta(regime: str | None, problem: str | None, report: dict, *, retired: bool) -> dict:
    """The facts the eyebrow shows: split regime, problem type, rows, whether the definition is built or retired."""
    return {
        "regime": regime,
        "problem": problem,
        "rows": (report.get("data") or {}).get("n_rows"),
        "built": bool((report.get("build") or {}).get("uuid")),
        "retired": retired,
    }


def _summary_from_class(cls: Any) -> dict | None:
    s = cls.task_summary
    if s is None:
        return None
    fields = s.fields()
    question, fit_reason = fields.pop("question"), fields.pop("fit_reason")
    return {"source": "definition", "fit": s.fit, "question": question, "fit_reason": fit_reason, "fields": fields}


def _summary_from_source(code: str) -> dict | None:
    """The ``task_summary = TaskSummary(...)`` of a committed dataset.py, read without importing it."""
    for node in ast.walk(ast.parse(code)):
        if (
            isinstance(node, ast.Assign)
            and any(isinstance(t, ast.Name) and t.id == "task_summary" for t in node.targets)
            and isinstance(node.value, ast.Call)
        ):
            try:
                kwargs = {kw.arg: ast.literal_eval(kw.value) for kw in node.value.keywords}
                fields = TaskSummary(**kwargs).fields()
            except (ValueError, TypeError):
                return None
            question, fit_reason = fields.pop("question"), fields.pop("fit_reason")
            return {
                "source": "retired",
                "fit": kwargs.get("fit"),
                "question": question,
                "fit_reason": fit_reason,
                "fields": fields,
            }
    return None


def _sentence(text: str) -> str:
    return text[:1].upper() + text[1:]


def _summary_from_tldr(text: str) -> dict:
    """A hand-written summary: split into the summary fields when its paragraphs are labelled, else HTML.

    Its use-case paragraph ("**Use case: none ....** why") gives the fit and the fit reason.
    """
    out: dict = {"source": "tldr", "fit": None, "question": "", "fit_reason": "", "fields": {}, "html": ""}
    for para in re.split(r"\n\s*\n", text.strip()):
        m = re.match(r"^\*\*(.+?)\*\*\s*(.*)$", para.strip(), re.S)
        if not m:
            return {"source": "tldr", "html": render(text)}
        label, body = m.group(1).strip(), m.group(2).strip()
        use = re.match(r"^Use case:\s*((direct|approximate|none)\b.*?)\.?$", label, re.I)
        if use:
            out["fit"] = use.group(2).lower()
            out["fields"]["use_case"] = _sentence(use.group(1)) + "."
            out["fit_reason"] = body
            continue
        key = TLDR_LABELS.get(label.rstrip(":.").strip().lower())
        if key is None:
            return {"source": "tldr", "html": render(text)}
        if key == "question":
            out["question"] = _sentence(body)
        else:
            out["fields"][key] = _sentence(body)
    return out


def _extra_crosscut(path: Path) -> list[dict]:
    sections = yaml.safe_load(path.read_text()) or []
    out = []
    for sec in sections if isinstance(sections, list) else [None]:
        if not isinstance(sec, dict) or "title" not in sec or not isinstance(sec.get("items"), list):
            raise BuildError(f"{path}: a list of sections, each {{title, items: [{{id, title, md}}]}}")
        items = []
        for it in sec["items"]:
            if not isinstance(it, dict) or not all(k in it for k in ("id", "title", "md")):
                raise BuildError(f"{path}, section {sec['title']!r}: each item has an id, a title and md")
            text = str(it["md"])
            items.append(
                {
                    "id": str(it["id"]),
                    "titleHtml": MD.renderInline(str(it["title"])),
                    "html": render(text),
                    "resolved": _is_resolved(text, str(it["title"])),
                },
            )
        out.append({"title": str(sec["title"]), "items": items})
    return out


def _date_text(day: dt.date) -> str:
    return f"{day.day} {day:%b %Y}"


@dataclass(frozen=True)
class _Repo:
    """Where the files are: the git repository, the working copy in it, and the GitHub base of the branch."""

    repo: Path
    root: Path
    wc: str
    github: str


def _repo_of(root: Path) -> _Repo:
    root = root.resolve()
    if not root.is_dir():
        raise BuildError(f"no folder {root}; run from the repository root or pass --root")
    top = _git(root, "rev-parse", "--show-toplevel", check=False)
    if top.returncode != 0:
        raise BuildError(f"{root} is not inside a git repository")
    repo = Path(top.stdout.strip())
    ref = _git(repo, "rev-parse", "--abbrev-ref", "HEAD").stdout.strip()
    if ref == "HEAD":
        ref = _git(repo, "rev-parse", "--short", "HEAD").stdout.strip()
    return _Repo(repo, root, root.relative_to(repo).as_posix(), f"{GITHUB_REPO}/blob/{ref}/")


def _live_definition(where: _Repo, name: str, folder: str) -> dict[str, Any]:
    """The code, use case, eyebrow facts and README of a definition in the working copy."""
    definition = where.root / folder / "dataset.py"
    if not definition.is_file():
        raise BuildError(f"{name}: {where.wc}/{folder}/ has no dataset.py")
    try:
        cls = load_definition(definition)
    except Exception as error:
        raise BuildError(f"{name}: {where.wc}/{folder}/dataset.py does not import: {error}") from error
    if cls.dataset_metadata.unique_name != folder:
        raise BuildError(f"{where.wc}/{folder}/dataset.py names `{cls.dataset_metadata.unique_name}`, not `{folder}`")
    regime = "grouped" if cls.grouping is not None else "temporal" if cls.temporal is not None else "iid"
    return {
        "code": definition.read_text(),
        "summary": _summary_from_class(cls),
        "meta": _meta(regime, cls.problem_type, read_report(where.root / folder / "README.md"), retired=False),
        "readme": _readme(where.root / folder, f"{where.wc}/{folder}", where.github),
    }


def _retired_definition(where: _Repo, name: str, folder: str) -> dict[str, Any]:
    """The same for a folder gone from the working copy, from the last commit that still had it."""
    path = f"{where.wc}/{folder}/dataset.py"
    found = _last_commit_with(where.repo, path)
    if found is None:
        raise BuildError(
            f"{name}: the outcome names the folder `{folder}`, but {path} is neither in the working copy "
            "nor in git history"
        )
    commit, removed_on = found
    code = _show(where.repo, commit, path)
    readme_at = _last_commit_with(where.repo, f"{where.wc}/{folder}/README.md")
    front, _ = _frontmatter(_show(where.repo, readme_at[0], f"{where.wc}/{folder}/README.md") if readme_at else None)
    task = front.get("task") or {}
    meta = None
    if code or front:
        regime = REGIME.get(task.get("split_regime"), task.get("split_regime"))
        meta = _meta(regime, task.get("problem_type"), front, retired=True)
    return {
        "code": code,
        "summary": _summary_from_source(code) if code else None,
        "meta": meta,
        "retiredCommit": _git(where.repo, "rev-parse", "--short", commit).stdout.strip(),
        "retiredDate": removed_on,
    }


def _dataset(where: _Repo, report: dict[str, Any], row: dict[str, Any], tldr: dict[str, Any]) -> dict[str, Any]:
    """Everything the page shows for one record."""
    name = row["name"]
    rec = report["records"][name]
    cat = _category(row["outcome"])
    m = re.search(r"added as `([^`]+)`", row["outcome"])
    folder = m.group(1) if m else (None if cat == "notadded" else name)
    record_path = where.repo / RECORDS_DIR / f"{name}.md"
    if not record_path.is_file():
        raise BuildError(f"{name}: no curation record {RECORDS_DIR}/{name}.md")
    retired = bool(folder) and not (where.root / folder).is_dir()
    files: dict[str, Any] = {"code": None, "summary": None, "meta": None, "readme": None}
    if folder:
        files.update(_retired_definition(where, name, folder) if retired else _live_definition(where, name, folder))
    if files["summary"] is None and name in tldr:
        files["summary"] = _summary_from_tldr(str(tldr[name]))
    decided = _decided(record_path)
    return {
        "name": name,
        "folder": folder,
        "late": row["late"],
        "cat": "decided" if decided else cat,
        "outcomeHtml": MD.renderInline(row["outcome"]),
        "pointsHtml": MD.renderInline(row["points"]),
        "issuesIntroHtml": render(rec["issues_intro"]),
        "items": [
            {
                "n": it["n"],
                "titleHtml": MD.renderInline(it["title_md"]),
                "html": render(it["body_md"]),
                "resolved": it["resolved"],
            }
            for it in rec["items"]
        ],
        "fields": report["fields"].get(name, []),
        "blocks": [
            {"key": k, "title": SECTION_TITLES[k], "html": render(v)} for k, v in rec["blocks"].items() if v.strip()
        ],
        "shared": [{"title": s["title"], "html": render(s["md"])} for s in report["shared"].get(name, [])],
        "code": files["code"],
        "retired": retired,
        "record": _record(record_path),
        "decided": decided,
        "summary": files["summary"],
        "meta": files["meta"],
        "readme": files["readme"],
        "retiredCommit": files.get("retiredCommit"),
        "retiredDate": files.get("retiredDate"),
    }


def _crosscut(report: dict[str, Any], extra: Path | None) -> list[dict[str, Any]]:
    crosscut = [
        {
            "title": sec["title"],
            "items": [
                {
                    "id": it["id"],
                    "titleHtml": MD.renderInline(it["title_md"]),
                    "html": render(it["body_md"]),
                    "resolved": it["resolved"],
                }
                for it in sec["items"]
            ],
        }
        for sec in report["crosscut"]
    ]
    if extra:
        crosscut += _extra_crosscut(extra)
    ids = [it["id"] for sec in crosscut for it in sec["items"]]
    if len(ids) != len(set(ids)):
        raise BuildError(f"cross-dataset ids appear twice: {sorted({i for i in ids if ids.count(i) > 1})}")
    return crosscut


def build_data(
    report: dict[str, Any],
    root: Path,
    *,
    title: str = "New Datasets Review",
    subtitle: str | None = None,
    tldr: Path | None = None,
    extra_crosscut: Path | None = None,
) -> dict[str, Any]:
    """The data the page renders: the parsed report plus each record's files as they are now.

    Raises:
        BuildError: A record, a definition or a retired definition named by the report is missing.
    """
    where = _repo_of(root)
    tldr_entries = (yaml.safe_load(tldr.read_text()) or {}) if tldr else {}
    datasets = [_dataset(where, report, row, tldr_entries) for row in report["rows"]]

    today = dt.date.today()
    run_date = dt.date.fromisoformat(report["date"]) if report["date"] else None
    if subtitle is None:
        n = len(datasets)
        when = f"run of {_date_text(run_date)}" if run_date else f"built {_date_text(today)}"
        subtitle = f"Working copy {where.root.name} · {n} curation record{'' if n == 1 else 's'} · {when}"
    path = Path(report["path"]).resolve()
    shown = path.relative_to(where.repo).as_posix() if path.is_relative_to(where.repo) else path.name
    return {
        "generated": (run_date or today).isoformat(),
        "snapshot": _date_text(today),
        "headerHtml": render(report["header_md"]),
        "datasets": datasets,
        "crosscut": _crosscut(report, extra_crosscut),
        "title": title,
        "subtitle": subtitle,
        "report": {"name": path.name, "path": shown, "title": report["title"], "date": report["date"]},
        "github": where.github,
        "githubRepo": GITHUB_REPO,
        "workingCopy": where.wc,
        "dashboard": DASHBOARD,
        "tldr": tldr.name if tldr else None,
    }


def _category(outcome: str) -> str:
    """added, noship or notadded (a record that triage already decided becomes `decided` later)."""
    if outcome.startswith("not added"):
        return "notadded"
    if "recommended" in outcome:
        return "noship"
    return "added"


def assemble(data: dict[str, Any], template: str) -> str:
    """The page: the template with the title, the subtitle and the data filled in."""
    missing = [p for p in PLACEHOLDERS if p not in template]
    if missing:
        raise BuildError(f"the template lacks the placeholder(s) {missing}")
    page = template.replace("__TITLE__", html.escape(data["title"])).replace(
        "__SUBTITLE__", html.escape(data["subtitle"])
    )
    # Inside <script>, "</" could close the element and "<!--" could start an escaped state; both are valid JSON
    # escapes inside strings, where alone they can occur.
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    payload = payload.replace("</", "<\\/").replace("<!--", "<\\u0021--")
    return page.replace("__DATA__", payload, 1)


def _report(data: dict[str, Any], out: Path) -> None:
    datasets = data["datasets"]
    n_items = sum(len(d["items"]) for d in datasets)
    n_open = sum(1 for d in datasets for it in d["items"] if not it["resolved"])
    n_fields = sum(len(d["fields"]) for d in datasets)
    n_x = sum(len(s["items"]) for s in data["crosscut"])
    print(
        f"records {len(datasets)}, issues {n_items} ({n_open} open), field rows {n_fields}, cross-dataset items {n_x}"
    )
    cats: dict[str, int] = {}
    for d in datasets:
        cats[d["cat"]] = cats.get(d["cat"], 0) + 1
    print("categories:", cats)
    by_source: dict[str, list[str]] = {}
    for d in datasets:
        by_source.setdefault((d["summary"] or {}).get("source", "none"), []).append(d["name"])
    print("summaries:", {k: len(v) for k, v in sorted(by_source.items())})
    for d in datasets:
        if d["folder"] and not d["summary"]:
            print(f"  no summary: {d['name']} (folder {d['folder']}{', retired' if d['retired'] else ''})")
    for name in ("data.json", "review_page.html"):
        print(f"{out / name} {(out / name).stat().st_size:,} bytes")


def main(argv: list[str] | None = None) -> int:
    """Parse the report, collect the files, write data.json and the page."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("report", type=Path, help="The run report (markdown).")
    parser.add_argument("--out", type=Path, required=True, help="Folder for data.json and review_page.html.")
    parser.add_argument("--root", type=Path, default=Path("datasets/_dev/tabarena-v0pt2"), help="The working copy.")
    parser.add_argument("--title", default="New Datasets Review", help="The page title.")
    parser.add_argument("--subtitle", help="Default: the working copy, the number of records and the report date.")
    parser.add_argument("--tldr", type=Path, help="YAML of hand-written summaries for records without task_summary.")
    parser.add_argument("--extra-crosscut", type=Path, help="YAML of cross-dataset sections not in the report.")
    args = parser.parse_args(argv)

    try:
        report = parse_report(args.report)
        data = build_data(
            report,
            args.root,
            title=args.title,
            subtitle=args.subtitle,
            tldr=args.tldr,
            extra_crosscut=args.extra_crosscut,
        )
        page = assemble(data, TEMPLATE.read_text())
    except ReportFormatError as error:
        print(f"error: {error}\nThe format: {HERE.parent / 'references' / 'run_report_format.md'}", file=sys.stderr)
        return 1
    except BuildError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "data.json").write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")))
    (args.out / "review_page.html").write_text(page)
    _report(data, args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
