ZOO_CHECKSUM = "v2:a5bd99c9e33cc0f2b8b09784ccfdb55946e5a0f7b73618f3c04d598b11f31108"
"""The checksum of the zoo's container, the same under pandas 2 and pandas 3."""


@pytest.mark.parametrize(
    ("values", "arrow", "expected"),
    [
        ([1.5, None], pa.float64(), "float64"),
        ([1.0, 2.0], pa.float32(), "float64"),
        ([1, 2], pa.int64(), "int64"),
        ([1, None], pa.int64(), "Int64"),
        ([1, 2], pa.uint8(), "uint8"),
        ([1, None], pa.int32(), "Int32"),
        ([True, False], pa.bool_(), "bool"),
        ([True, None], pa.bool_(), "boolean"),
        (["a", None], pa.string(), "object"),
    ],
    ids=str,
)
def test_an_arrow_backed_column_gets_the_dtype_pandas_2_gives(values: list, arrow: pa.DataType, expected: str) -> None:
    """A cast that starts from the ``string`` dtype is Arrow-backed in pandas 3; the container stores what pandas 2
    gives for the same values.
    """
    out = canonical_dtypes(pd.DataFrame({"c": pd.Series(values, dtype=pd.ArrowDtype(arrow))}))["c"]
    assert str(out.dtype) == expected
    assert out.isna().tolist() == [v is None for v in values]


def test_an_arrow_timestamp_keeps_its_time_zone_in_nanoseconds() -> None:
    column = pd.Series(pd.to_datetime(["2024-01-01 10:00", None]).tz_localize("UTC")).astype(
        pd.ArrowDtype(pa.timestamp("us", tz="UTC"))
    )
    out = canonical_dtypes(pd.DataFrame({"c": column}))["c"]
    assert str(out.dtype) == "datetime64[ns, UTC]"
    assert out.iloc[0] == pd.Timestamp("2024-01-01 10:00", tz="UTC")
    assert pd.isna(out.iloc[1])


def test_pandas_2_and_3_build_the_same_container_from_a_frame(warehouse: Path) -> None:
    """A definition whose raw frame is built in code (no file parser in between) has one checksum under both pandas
    versions: categoricals with missing values, an ordinal, nullable integers, booleans, text, time-zone datetimes
    across a daylight-saving change, and a float parsed from text with the ``string`` dtype.
    """
    (warehouse / "dtype_zoo").mkdir()
    container = load_definition_from_text(ZOO, "dtype_zoo")().to_container()
    assert container.dataset["price_per_gram"].dtype == "float64"
    assert container.checksum == ZOO_CHECKSUM


CSV_TEXT = "x,y\n" + "".join(
    f"{v:.17g},{i % 2}\n" for i, v in enumerate(np.random.default_rng(3).uniform(-90, 90, 400))
)

CSV_PARSED = {2: "1185442199", 3: "3504554658"}
"""A hash of the floats ``pd.read_csv`` parses from :data:`CSV_TEXT`, per pandas major version: they differ."""


def test_pandas_versions_parse_csv_floats_as_pinned(tmp_path: Path) -> None:
    """The pandas 3 CSV parser reads every float exactly; pandas 2's default rounds some in the last bit. A dataset read
    from a CSV with long floats therefore gets another checksum under pandas 3 (fiat_500's coordinates). If this
    starts failing, pandas changed its parser again: build the working copy with one pandas version.
    """
    path = tmp_path / "floats.csv"
    path.write_text(CSV_TEXT)
    parsed = pd.read_csv(path)["x"].to_numpy()
    exact = np.array([float(line.split(",")[0]) for line in CSV_TEXT.splitlines()[1:]])
    digest = pd.util.hash_array(parsed).sum() % (1 << 32)
    assert str(digest) == CSV_PARSED[PANDAS_MAJOR]
    assert (parsed == exact).all() == (PANDAS_MAJOR >= 3)
