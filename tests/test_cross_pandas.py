"""pandas 2 and pandas 3 build the same container, except where pandas itself reads a file differently.

CI runs the suite under both (Python 3.10 with pandas 2, Python 3.12 with pandas 3), so a pinned checksum here fails
in the job whose pandas builds something else. On 2026-11-27 a pandas 3 build of 15 definitions gave three other
checksums: coffee_rating_prediction got a ``double[pyarrow]`` column (fixed in ``canonical_dtypes``), and
airqo_low_cost_air_quality_monitor_calibration_challenge and fiat_500 read their CSV floats differently, because
pandas 3 parses every float exactly where pandas 2 rounds some in the last bit (``float_precision``). The working
copy is built with pandas 2, the version the repository locks.

When a golden test fails after a deliberate change to what a container holds, recompute the constant under both
pandas versions and update it with the reason.
"""

