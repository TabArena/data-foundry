@pytest.fixture
def warehouse(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    root = tmp_path / "warehouse"
    folder = root / "shops"
    folder.mkdir(parents=True)
    rng = np.random.default_rng(0)
    for shop in ("north", "south", "east", "west"):
        n = 50
        pd.DataFrame(
            {
                "temperature": rng.normal(15, 5, n).round(1),
                "promotion": rng.integers(0, 2, n),
                "customers": rng.integers(50, 150, n),
                "revenue": rng.normal(1000, 100, n).round(2),
            }
        ).to_csv(folder / f"{shop}.csv", index=False)
    monkeypatch.setenv(DATA_FOUNDRY_WAREHOUSE_ENV, str(root))
    return root


def write(root: Path, name: str, text: str) -> Path:
    folder = root / name
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "dataset.py").write_text(text)
    return folder


def shops(files: str = '"*.csv"', extra_non_features: str = "", body: str = "") -> str:
    """The definition of the shops dataset, the revenue as its target."""
    return SHOPS.format(files=files, extra_non_features=extra_non_features, body=body)


@pytest.fixture
def root(tmp_path: Path, warehouse: Path) -> Path:
    del warehouse
    folder = tmp_path / "datasets"
    write(folder, "shops", shops())
    return folder


def test_read_files_stacks_the_files_and_records_where_each_row_comes_from(warehouse: Path) -> None:
    df = read_files(warehouse / "shops", "*.csv")
    assert list(df["source_file"].unique()) == ["east.csv", "north.csv", "south.csv", "west.csv"]  # sorted
    assert df.groupby("source_file")["source_row"].agg(["min", "max"]).to_numpy().tolist() == [[1, 50]] * 4
    assert df["source_id"].str.fullmatch(r"[0-9a-f]{16}").all()
    reordered = read_files(warehouse / "shops", "east.csv").iloc[::-1]
    shuffled = pd.read_csv(warehouse / "shops" / "east.csv").iloc[::-1]
    shuffled.to_csv(warehouse / "shops" / "east.csv", index=False)
    again = read_files(warehouse / "shops", "east.csv")
    assert set(again["source_id"]) == set(reordered["source_id"])  # the id survives a re-saved, reordered file
    with_ids = read_files(warehouse / "shops", "north.csv", id_column="promotion")
    assert set(with_ids["source_id"]) <= {"0", "1"}
    with pytest.raises(FileNotFoundError, match="No file matches"):
        read_files(warehouse / "shops", "*.parquet")


def test_a_task_drops_the_declared_columns_it_gives_no_role(root: Path) -> None:
    task = get_dataset(root, "shops")
    result = task.check(write_report=False, verbose=False)
    assert result.ok
    columns = set(result.container.dataset.columns)
    assert columns == {"temperature", "promotion", "revenue", "shop"}  # the target, a declared outcome, stays
    assert [nf.column for nf in task.dropped_non_features] == ["customers", "source_file", "source_row", "source_id"]


def test_a_declared_column_used_as_the_group_key_stays(root: Path) -> None:
    grouping = (
        '    grouping = Grouping(on="source_file", labels="per_sample", definition="One file is one shop; shops are '
        'held out.")\n'
    )
    write(root, "shops", shops(body=grouping))
    result = get_dataset(root, "shops").check(write_report=False, verbose=False)
    assert "source_file" in result.container.dataset.columns
    assert result.container.task_metadata.group_on == "source_file"


def test_the_readme_lists_the_non_features_and_the_raw_files(root: Path) -> None:
    get_dataset(root, "shops").check(verbose=False)
    assert sorted(read_report(root / "shops" / "README.md")["raw_files"]) == [
        "east.csv",
        "north.csv",
        "south.csv",
        "west.csv",
    ]
    task = (root / "shops" / "README.md").read_text()
    assert (
        "Dropped as no features (declared in `non_features`): `customers` (outcome), `source_file` (provenance)" in task
    )
    assert "The 4 raw files the sources name" in task or "| `east.csv` |" in task


@pytest.mark.parametrize(
    ("extra", "match"),
    [
        ('        NonFeature("x", "guess"),\n', "is one of outcome"),
        ('        NonFeature("x", "other"),\n', "says why in its `description`"),
        ('        NonFeature("revenue", "outcome"),\n', "declares \\['revenue'\\] twice"),
    ],
)
def test_the_rules_of_the_declarations(root: Path, extra: str, match: str) -> None:
    folder = write(root, "shops", shops(extra_non_features=extra))
    with pytest.raises(DatasetDefinitionError, match=match):
        load_definition(folder)


def test_a_misspelled_declaration_fails_the_run(root: Path) -> None:
    write(root, "shops", shops(extra_non_features='        NonFeature("custmers", "outcome"),\n'))
    with pytest.raises(DatasetDefinitionError, match=r"`non_features` names \['custmers'\]"):
        get_dataset(root, "shops").check(write_report=False, verbose=False)


def test_the_manifest_hashes_each_file_once_and_counts_its_rows(
    root: Path, warehouse: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    calls = []
    real = dataset_module._sha256
    monkeypatch.setattr(dataset_module, "_sha256", lambda path: calls.append(path.name) or real(path))
    task = get_dataset(root, "shops")
    manifest = task.check(write_report=False, verbose=False).container.dataset_metadata.raw_files
    assert [(f.path, f.rows, f.source) for f in manifest] == [
        (name, 50, "Other publication") for name in ("east.csv", "north.csv", "south.csv", "west.csv")
    ]
    assert manifest[0].sha256 == real(warehouse / "shops" / "east.csv")
    assert len(calls) == 4
    task.raw_manifest()  # unchanged files: read from the cache
    assert len(calls) == 4
    path = warehouse / "shops" / "east.csv"
    path.write_text(path.read_text().replace("\n", "\n", 1) + "1.0,0,1,1.0\n")
    os.utime(path, ns=(path.stat().st_atime_ns, path.stat().st_mtime_ns + 10**9))
    task.raw_manifest()
    assert calls[-1] == "east.csv"


def test_a_changed_raw_file_is_reported_against_the_readme(root: Path, warehouse: Path) -> None:
    get_dataset(root, "shops").check(verbose=False)
    path = warehouse / "shops" / "north.csv"
    path.write_text(path.read_text() + "15.0,0,100,999.0\n")
    result = get_dataset(root, "shops").check(write_report=False, verbose=False)
    finding = next(r for r in result.bundle_report.results if r.slug == "raw_files_changed")
    assert "changed: ['north.csv']" in finding.message


def test_a_pattern_that_matches_no_file_is_an_error(root: Path) -> None:
    write(root, "shops", shops(files='"*.csv", "extra/*.parquet"'))
    result = get_dataset(root, "shops").check(write_report=False, verbose=False)
    assert "raw_files_missing" in {r.slug for r in result.bundle_report.errors}


def test_a_dense_unique_integer_column_is_flagged_as_a_running_id() -> None:
    df = pd.DataFrame({"row_id": np.arange(100, 200), "price": np.arange(100) * 1000, "target": np.tile([0, 1], 50)})
    slugs = {r.slug: r.message for r in run_bundle_checks(make_container(df), verbose=False).results}
    assert "running id: ['row_id']" in slugs["dataset_identifier_column"]  # `price` is unique too, but spread out


def test_the_order_column_of_a_label_time_split_is_not_flagged_as_a_running_id() -> None:
    """A rebuilt order the split cuts on (SPLIT-22) is a running id by construction and no model input."""
    df = pd.DataFrame({"row_id": np.arange(100, 200), "price": np.arange(100) * 1000, "target": np.tile([0, 1], 50)})

    def task(**extra) -> PredictiveMLTaskMetadataV2:
        return PredictiveMLTaskMetadataV2(
            target_column_name="target",
            problem_type="binary_classification",
            objective_metric=make_spec("binary_classification"),
            time_on="row_id",
            **extra,
        )

    label_time = run_bundle_checks(make_container(df, task_metadata=task(time_of="label")), verbose=False)
    assert "dataset_identifier_column" not in {r.slug for r in label_time.results}
    # the label time is what exempts it: as the prediction point the column is a running id a model reads
    prediction_time = run_bundle_checks(make_container(df, task_metadata=task()), verbose=False)
    assert "dataset_identifier_column" in {r.slug for r in prediction_time.results}
