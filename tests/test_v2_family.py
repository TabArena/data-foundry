PARENT = """
from __future__ import annotations

from pathlib import Path

import pandas as pd
from data_foundry.v2 import AbstractCuratedDataset, DataSummary, FeatureTypes, Source


class ToyFamily(AbstractCuratedDataset):
    data_summary = DataSummary(
        data="Generated measurements of a test bench.",
        row="One generated measurement.",
        goals="Testing families of definitions.",
    )
    unique_name = "toy_family"
    domain = "handcrafted"
    sources = (
        Source(
            role="publication",
            platform="Other",
            url="https://example.org/toy",
            license="CC0",
            year="2024",
            bibtex="@misc{{toy2024, title = {{Toy}}, author = {{Tester}}, year = {{2024}}}}",
        ),
    )
    download_description = "Generated by the test."
    curation_comments = "Toy data with two outcomes, y and z."
{extra}
    def _load_raw(self, raw_dir: Path) -> pd.DataFrame:
        return pd.read_csv(raw_dir / "toy.csv")

    def _clean(self, raw: pd.DataFrame) -> pd.DataFrame:
        df = raw.drop(columns=["row_id"])
        df["y"] = df["y"].map({{0: "no", 1: "yes"}})
        return df

    def _feature_types(self, df: pd.DataFrame) -> FeatureTypes:
        return FeatureTypes(categorical=["colour"])
"""

SUMMARY = """TaskSummary(
        question="Is a generated measurement positive?",
        use_case="A tester checks that a family runs end to end.",
        row="One generated measurement.",
        predicted="{what}",
        known="A number and a colour.",
        split="Random measurements.",
        fit="direct",
        fit_reason="The data is generated for the test.",
    )"""

CHILD = """
from __future__ import annotations

from data_foundry.v2 import Metric, TaskSummary, import_definition

{parent_class} = import_definition("{parent}")


class {class_name}({parent_class}):
    unique_name = "{name}"
    derivation = "{derivation}"
{body}"""

CHILD_Y = """    task_summary = {summary}
    target = "y"
    problem_type = "binary_classification"
    metric = Metric.fallback(reason="the toy data has no source metric")

    def _clean(self, raw):
        return super()._clean(raw).drop(columns=["z"])  # the other outcome
""".format(summary=SUMMARY.format(what="A yes/no label."))

CHILD_Z = """    task_summary = {summary}
    target = "z"
    problem_type = "regression"
    metric = Metric.fallback(reason="the toy data has no source metric")

    def _clean(self, raw):
        return super()._clean(raw).drop(columns=["y"])  # the other outcome
""".format(summary=SUMMARY.format(what="A number."))


@pytest.fixture
def warehouse(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A temporary warehouse holding the family's raw file."""
    root = tmp_path / "warehouse"
    rng = np.random.default_rng(0)
    x1 = rng.normal(size=300)
    raw = pd.DataFrame(
        {
            "row_id": np.arange(300),
            "x1": x1,
            "colour": rng.choice(["red", "green", "blue"], size=300),
            "y": rng.integers(0, 2, size=300),
            "z": 2 * x1 + rng.normal(size=300),
        },
    )
    (root / "toy_family").mkdir(parents=True)
    raw.to_csv(root / "toy_family" / "toy.csv", index=False)
    monkeypatch.setenv(DATA_FOUNDRY_WAREHOUSE_ENV, str(root))
    return root


def write(root: Path, name: str, text: str) -> Path:
    folder = root / name
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "dataset.py").write_text(text)
    return folder


def child(name: str, body: str, *, parent: str = "toy_family", derivation: str = "The other target.") -> str:
    class_name = "".join(part.capitalize() for part in name.split("_"))
    parent_class = "".join(part.capitalize() for part in parent.split("_"))
    return CHILD.format(
        parent=parent, parent_class=parent_class, class_name=class_name, name=name, derivation=derivation, body=body
    )


@pytest.fixture
def family(tmp_path: Path, warehouse: Path) -> Path:
    """A root with the parent `toy_family` and its children `toy_family_y` (classification) and `toy_family_z`."""
    del warehouse
    root = tmp_path / "datasets"
    write(root, "toy_family", PARENT.format(extra=""))
    write(root, "toy_family_y", child("toy_family_y", CHILD_Y, derivation="The yes/no label y as the target."))
    write(root, "toy_family_z", child("toy_family_z", CHILD_Z, derivation="The number z as the target."))
    return root


def test_a_family_is_one_parent_and_its_tasks(family: Path, warehouse: Path) -> None:
    definitions = discover_definitions(family)
    assert sorted(definitions) == ["toy_family", "toy_family_y", "toy_family_z"]
    assert sorted(discover_datasets(family)) == ["toy_family_y", "toy_family_z"]  # the tasks only
    assert not is_task(definitions["toy_family"])
    cop = get_dataset(family, "toy_family_y")
    assert [k.unique_name for k in lineage(type(cop))] == ["toy_family_y", "toy_family"]
    assert cop.raw_dir == warehouse / "toy_family"  # the family root's raw files
    meta = cop.dataset_metadata
    assert (meta.derived_from, meta.derivation) == ("toy_family", "The yes/no label y as the target.")
    assert meta.publication.year == "2024"  # inherited from the parent
    assert (
        cop.data_summary is definitions["toy_family"].data_summary
        or cop.data_summary.row == "One generated measurement."
    )


def test_each_child_keeps_its_target_and_drops_the_other_outcome(family: Path) -> None:
    y = get_dataset(family, "toy_family_y").check(write_report=False, verbose=False)
    z = get_dataset(family, "toy_family_z").check(write_report=False, verbose=False)
    assert y.ok
    assert z.ok
    assert set(y.container.dataset.columns) == {"x1", "colour", "y"}
    assert set(z.container.dataset.columns) == {"x1", "colour", "z"}
    assert y.container.dataset_metadata.derived_from == z.container.dataset_metadata.derived_from == "toy_family"
    assert y.container.task_metadata.problem_type == "binary_classification"
    assert z.container.task_metadata.problem_type == "regression"


def test_a_child_readme_links_its_parent_and_shows_the_data_summary(family: Path) -> None:
    get_dataset(family, "toy_family_y").check(verbose=False)
    readme = (family / "toy_family_y" / "README.md").read_text()
    assert read_report(family / "toy_family_y" / "README.md")["parent"] == "toy_family"
    assert "Derived from [`toy_family`](../toy_family/README.md): The yes/no label y as the target." in readme
    assert readme.index("## About the data") < readme.index("## In brief")
    assert "[`../toy_family/dataset.py`](../toy_family/dataset.py)" in readme


def test_a_parent_is_checked_never_built(family: Path) -> None:
    parent = get_dataset(family, "toy_family")
    result = parent.check(verbose=False)
    assert result.ok
    assert result.children == ["toy_family_y", "toy_family_z"]
    assert list(result.frame.columns) == ["x1", "colour", "y", "z"]
    assert result.data_checksum == data_checksum(parent.df) == parent.check(write_report=False).data_checksum
    front = read_report(family / "toy_family" / "README.md")
    assert (front["kind"], front["children"], front["data"]["n_rows"]) == (
        "parent",
        ["toy_family_y", "toy_family_z"],
        300,
    )
    readme = (family / "toy_family" / "README.md").read_text()
    assert "- [`toy_family_y`](../toy_family_y/README.md)" in readme
    with pytest.raises(DatasetDefinitionError, match="never built"):
        parent.build(verbose=False)


