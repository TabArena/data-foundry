    assert 'ToyFamily = import_definition("toy_family")' in text
    assert "class ToyFamilyW(ToyFamily):" in text
    assert "TODO(verify)" in text
    assert _cli(family, "new", "other_w", "--parent", "toy_family") == 1  # not named after its parent
