def test_an_inherited_summary_must_fit_the_task(family: Path, warehouse: Path) -> None:
    budget = "    row_budget = RowBudget(train=100, test=50)\n"
    same = child("toy_family_y_0p1k", budget, parent="toy_family_y", derivation="Sub-sampled to 100 / 50 rows.")
    folder = write(family, "toy_family_y_0p1k", same.replace("import Metric,", "import Metric, RowBudget,"))
    version = load_definition(folder)()
    assert version.task_summary == load_definition(family / "toy_family_y").task_summary  # same task: inherited
    assert version.raw_dir == warehouse / "toy_family"  # the root's raw files, through two generations
    assert version.dataset_metadata.derived_from == "toy_family_y"
    other = child(
        "toy_family_y_z",
        '    target = "z"\n    problem_type = "regression"\n',
        parent="toy_family_y",
        derivation="z as the target.",
    )
    folder = write(family, "toy_family_y_z", other)
    with pytest.raises(DatasetDefinitionError, match="`task_summary` is inherited from `toy_family_y`"):
        load_definition(folder)


def test_import_definition_refuses_a_circle(tmp_path: Path) -> None:
    root = tmp_path / "datasets"
    write(root, "loop_a", 'from data_foundry.v2 import import_definition\n\nB = import_definition("loop_b")\n')
    write(root, "loop_b", 'from data_foundry.v2 import import_definition\n\nA = import_definition("loop_a")\n')
    with pytest.raises(ImportError, match="import each other in a circle"):
        load_definition(root / "loop_a")


def test_a_parent_edit_reaches_the_child_in_the_workbench(family: Path) -> None:
    ds = workbench(family / "toy_family_y")
    assert "x2" not in ds.df.columns
    raw_before = ds.raw
    parent_file = family / "toy_family" / "dataset.py"
    text = parent_file.read_text().replace(
        '        df["y"] = df["y"].map', '        df["x2"] = df["x1"] * 2\n        df["y"] = df["y"].map'
    )
    parent_file.write_text(text)
    later = time.time() + 5
    os.utime(parent_file, (later, later))  # a new modification time even on a coarse file system
    assert "x2" in ds.df.columns
    assert ds.raw is raw_before  # `_load_raw` is unchanged, so the raw data stays cached


def test_unseeded_randomness_in_the_parent_is_a_finding_of_the_child(family: Path) -> None:
    parent_file = family / "toy_family" / "dataset.py"
    parent_file.write_text(
        parent_file.read_text().replace(
            '        df = raw.drop(columns=["row_id"])', '        df = raw.drop(columns=["row_id"]).sample(frac=1)'
        )
    )
    result = get_dataset(family, "toy_family_y").check(write_report=False, verbose=False)
    finding = next(r for r in result.bundle_report.errors if r.slug == "definition_nondeterministic")
    assert finding.message.startswith("../toy_family/dataset.py has 1 call(s)")


def test_a_class_from_a_notebook_is_checked_without_a_page(family: Path) -> None:
    parent = load_definition(family / "toy_family")
    attributes = {
        "__module__": "a_notebook_cell",  # no file, as in a notebook
        "unique_name": "toy_family_try",
        "derivation": "Trying z as a target.",
        "task_summary": TaskSummary(
            question="q?", use_case="u", row="r", predicted="p", known="k", split="s", fit="direct", fit_reason="f"
        ),
        "target": "z",
        "problem_type": "regression",
        "metric": Metric.fallback(reason="the toy data has no source metric"),
    }
    trial = type("Try", (parent,), attributes)()
    assert trial.folder is None
    result = trial.check(verbose=False)  # no README to write
    assert result.container.dataset_metadata.derived_from == "toy_family"
    assert not list((family / "toy_family").glob("README.md"))
    with pytest.raises(DatasetDefinitionError, match=r"defined outside a `dataset\.py`"):
        trial.build(verbose=False)


def test_a_child_prepares_the_raw_files_of_the_root(tmp_path: Path, warehouse: Path) -> None:
    root = tmp_path / "datasets"
    extra = (
        '    prepared_raw_files = ("toy.parquet",)\n\n'
        "    def _prepare_raw_files(self, raw_dir: Path) -> None:\n"
        '        pd.read_csv(raw_dir / "toy.csv").to_parquet(raw_dir / "toy.parquet")\n'
    )
    write(root, "toy_family", PARENT.format(extra=extra))
    write(root, "toy_family_y", child("toy_family_y", CHILD_Y))
    kid = get_dataset(root, "toy_family_y")
    _ = kid.raw
    assert (warehouse / "toy_family" / "toy.parquet").is_file()
    assert _prepare_code_hash(type(kid)) == _prepare_code_hash(load_definition(root / "toy_family"))
    assert PREPARED_MARKER in {p.name for p in (warehouse / "toy_family").iterdir()}
    override = CHILD_Y + "\n    def _prepare_raw_files(self, raw_dir):\n        pass\n"
    folder = write(root, "toy_family_y", child("toy_family_y", override))
    with pytest.raises(DatasetDefinitionError, match="`_prepare_raw_files`: the raw files belong to `toy_family`"):
        load_definition(folder)


def _cli(root: Path, *argv: str) -> int:
    parser = argparse.ArgumentParser()
    add_dataset_parser(parser.add_subparsers(dest="command"))
    args = parser.parse_args(["dataset", *argv, "--root", str(root)])
    args.records_dir = str(root / "no_records")
    return args.func(args)


def test_cli_lists_the_family_and_refuses_to_build_a_parent(family: Path, capsys: pytest.CaptureFixture) -> None:
    assert _cli(family, "list") == 0
    out = capsys.readouterr().out
    assert "toy_family " in out
    assert "parent" in out
    assert "<- toy_family" in out
    assert "2 dataset(s) and 1 parent(s)" in out
    assert _cli(family, "build", "toy_family") == 1


def test_cli_new_scaffolds_a_child(family: Path) -> None:
    assert _cli(family, "new", "toy_family_w", "--parent", "toy_family") == 0
