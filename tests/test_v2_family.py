def test_a_partial_parent_shares_code_only(tmp_path: Path, warehouse: Path) -> None:
    root = tmp_path / "datasets"
    partial = """
from __future__ import annotations

import pandas as pd
from data_foundry.v2 import AbstractCuratedDataset, DataSummary, FeatureTypes


class ToyFamily(AbstractCuratedDataset):
    data_summary = DataSummary(data="Measurements.", row="One measurement.", goals="Tests.")
    unique_name = "toy_family"

    def _clean(self, raw: pd.DataFrame) -> pd.DataFrame:
        return raw.drop(columns=["row_id", "z"])

    def _feature_types(self, df: pd.DataFrame) -> FeatureTypes:
        return FeatureTypes(categorical=["colour", "y"])
"""
    write(root, "toy_family", partial)
    body = PARENT.split("class ToyFamily(AbstractCuratedDataset):")[1]
    attributes = body[body.index("    domain =") : body.index("    curation_comments")]
    loader = (
        "    def _load_raw(self, raw_dir):\n"
        '        import pandas as pd\n\n        return pd.read_csv(raw_dir / "toy.csv")\n'
    )
    task = CHILD_Y.split("    def _clean")[0]
    text = child("toy_family_y", attributes + task + loader).replace(
        "from data_foundry.v2 import", "from data_foundry.v2 import Source,", 1
    )
    write(root, "toy_family_y", text)
    with pytest.raises(DatasetDefinitionError, match="partial parent"):
        get_dataset(root, "toy_family")
    assert _cli(root, "check", "toy_family") == 1
    (warehouse / "toy_family_y").mkdir()  # a child that says how to download its files reads its own folder
    (warehouse / "toy_family_y" / "toy.csv").write_bytes((warehouse / "toy_family" / "toy.csv").read_bytes())
    kid = get_dataset(root, "toy_family_y")
    assert kid.raw_dir == warehouse / "toy_family_y"
    result = kid.check(write_report=False, verbose=False)
    assert [r.slug for r in result.bundle_report.errors] == []
    assert set(result.container.dataset.columns) == {"x1", "colour", "y"}


@pytest.mark.parametrize(
    ("name", "body", "derivation", "match"),
    [
        ("toy_family_y", CHILD_Y, "", "declares `derivation`"),
        ("other_y", CHILD_Y, "x", "is named `toy_family_<variant>`"),
        ("toy_family_y", CHILD_Y + '    download_description = "x"\n', "x", "the raw files belong to `toy_family`"),
    ],
)
def test_the_rules_of_a_child(family: Path, name: str, body: str, derivation: str, match: str) -> None:
    folder = write(family, name, child(name, body, derivation=derivation))
    with pytest.raises(DatasetDefinitionError, match=match):
        load_definition(folder)


