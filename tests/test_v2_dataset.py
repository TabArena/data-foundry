def test_clean_changes_never_reach_the_raw_cache(tmp_path: Path, warehouse: Path) -> None:
    del warehouse
    body = (
        DEFINITION.format(name="toy_ds", comment="x")
        .replace(
            '        df["y"] = df["y"].map({0: "no", 1: "yes"})',
            '        df["y"] = df["y"].map({0: "no", 1: "yes"})\n'
            '        df.loc[df["x1"] > 0, "x1"] = 0.0\n'
            '        df.drop(columns=["colour"], inplace=True)',
        )
        .replace('categorical=["colour"]', "categorical=[]")
    )
    write_definition(tmp_path / "datasets", body=body)
    ds = get_dataset(tmp_path / "datasets", "toy_ds")
    raw_x1 = ds.raw["x1"].copy()
    _ = ds.df
    ds.check(write_report=False, verbose=False)
    assert ds.raw["x1"].equals(raw_x1)
    assert "colour" in ds.raw.columns
    assert ds.raw["y"].isin([0, 1]).all()


