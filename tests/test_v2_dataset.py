def test_check_writes_a_deterministic_report(tmp_path: Path, warehouse: Path) -> None:
    del warehouse
    folder = write_definition(tmp_path / "datasets")
    ds = get_dataset(tmp_path / "datasets", "toy_ds")

    result = ds.check(verbose=False)
    first = (folder / "report.md").read_text()
    ds.reload().check(verbose=False)

    assert result.ok, result.bundle_report.summary()
    assert not result.saved
    assert (folder / "report.md").read_text() == first
    fm = read_report(folder / "report.md")
    assert fm["unique_name"] == "toy_ds"
    assert fm["build"] is None
    assert fm["checksum"] == result.container.checksum
    assert fm["splits"]["n_repeats"] == 20  # 600 rows: 20-repeated 3-fold
    assert fm["splits"]["random_state"] == 4267
    assert result.container.experiment_metadata.splits_comment == "Default splits."


def test_build_records_uuid_and_a_later_edit_marks_it_stale(tmp_path: Path, warehouse: Path) -> None:
    folder = write_definition(tmp_path / "datasets")
    ds = get_dataset(tmp_path / "datasets", "toy_ds")

    built = ds.build(verbose=False)

    assert built.saved
    assert (warehouse / "toy_ds" / built.container.uuid / "dataset.parquet").is_file()
    fm = read_report(folder / "report.md")
    assert fm["build"]["uuid"] == built.container.uuid
    assert fm["build"]["path"] == f"toy_ds/{built.container.uuid}"
    assert fm["build_stale"] is False

    ds.check(verbose=False)
    assert read_report(folder / "report.md")["build"]["uuid"] == built.container.uuid

    write_definition(tmp_path / "datasets", comment="Toy data, edited.")
    ds.reload().check(verbose=False)
    fm = read_report(folder / "report.md")
    assert fm["build"]["uuid"] == built.container.uuid
    assert fm["build_stale"] is True


