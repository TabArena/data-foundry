DEFINITION = '''
from __future__ import annotations

from pathlib import Path

import pandas as pd

from data_foundry.v2 import AbstractCuratedDataset, FeatureTypes, drop_columns


class Toy(AbstractCuratedDataset):
    unique_name = "{name}"
    year = "2024"
    domain = "handcrafted"
    source = "Other"
    source_url = "https://example.org/toy"
    license = "CC0"
    download_description = """
        Generated by the test.
    """
    bibtex = """
        @misc{{toy2024,
          author = {{Tester}},
          title = {{Toy}},
          year = {{2024}}
        }}
    """
    curation_comments = "{comment}"

    target = "y"
    problem_type = "binary_classification"

    def _load_raw(self, raw_dir: Path) -> pd.DataFrame:
        return pd.read_csv(raw_dir / "toy.csv")

    def _clean(self, raw: pd.DataFrame) -> pd.DataFrame:
        df = raw
        df["y"] = df["y"].map({{0: "no", 1: "yes"}})
        return drop_columns(df, ["row_id"])

    def _feature_types(self, df: pd.DataFrame) -> FeatureTypes:
        return FeatureTypes(categorical=["colour"])
'''


@pytest.fixture
def warehouse(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A temporary warehouse holding the toy raw file."""
    root = tmp_path / "warehouse"
    rng = np.random.default_rng(0)
    raw = pd.DataFrame(
        {
            "row_id": np.arange(600),
            "x1": rng.normal(size=600),
            "colour": rng.choice(["red", "green", "blue"], size=600),
            "y": rng.integers(0, 2, size=600),
        },
    )
    (root / "toy_ds").mkdir(parents=True)
    raw.to_csv(root / "toy_ds" / "toy.csv", index=False)
    monkeypatch.setenv(DATA_FOUNDRY_WAREHOUSE_ENV, str(root))
    return root


def write_definition(root: Path, name: str = "toy_ds", *, comment: str = "Toy data.", body: str | None = None) -> Path:
    """Write ``<root>/<name>/dataset.py`` and return the folder."""
    folder = root / name
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / "dataset.py"
    path.write_text(DEFINITION.format(name=name, comment=comment) if body is None else body)
    # a rewrite within the same second must still change the mtime that auto-reload looks at
    stamp = time.time() + len(path.read_text()) % 7 + 1
    os.utime(path, (stamp, stamp))
    return folder


def load_definition_from_text(text: str, name: str) -> type[AbstractCuratedDataset]:
    """Load a definition from source text via a temporary folder named ``name``."""
    folder = Path(tempfile.mkdtemp()) / name
    folder.mkdir()
    (folder / "dataset.py").write_text(text)
    return load_definition(folder)


def test_flat_attributes_build_the_metadata() -> None:
    cls = load_definition_from_text(DEFINITION.format(name="toy_meta", comment="x"), "toy_meta")
    meta, task = cls.dataset_metadata, cls.task_metadata
    assert meta.download_description == "Generated by the test."
    assert meta.academic_reference_bibtex.startswith("@misc{toy2024,\n  author")
    assert meta.academic_reference_bibtex_key == "toy2024"
    assert meta.data_tags == ["IID"]
    assert task.objective_metric_name == "roc_auc"
    assert task.stratify_on == "y"


